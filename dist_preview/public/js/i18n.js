function changeLanguage(lang) {
    console.log('Changing language to:', lang);
    
    // 更新 HTML 文本
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // 翻译 Placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    // 更新文档方向和字体
    if (lang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
        document.body.style.fontFamily = "'Noto Sans Arabic', sans-serif";
        document.body.classList.add('rtl-mode');
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
        document.body.style.fontFamily = "'Marcellus', serif";
        document.body.classList.remove('rtl-mode');
    }
    
    // 移除所有 active 类
    document.querySelectorAll('.lang-menu a').forEach(a => a.classList.remove('active'));
    // 为当前选中的添加 active 类
    const activeLink = document.querySelector(`.lang-menu a[onclick*="'${lang}'"]`);
    if (activeLink) {
        activeLink.classList.add('active');
    }

    // 保存语言设置到 localStorage
    localStorage.setItem('selected-lang', lang);
}

// 暴露全局翻译函数以便其他脚本调用
window.applyTranslations = () => {
    const lang = localStorage.getItem('selected-lang') || 'en';
    changeLanguage(lang);
};

// 页面加载时初始化语言
document.addEventListener('DOMContentLoaded', () => {
    window.applyTranslations();
});
